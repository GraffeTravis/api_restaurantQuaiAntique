<?php

namespace App\Tests\Integration;

use App\Entity\Booking;
use App\Entity\Restaurant;
use App\Entity\User;
use App\Message\SyncBookingAnalytics;
use App\Repository\BookingAnalyticsRepository;
use App\Service\BookingStatistics;
use App\Service\BookingStatisticsFilter;
use Doctrine\DBAL\Connection;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Tools\SchemaTool;
use MongoDB\Client;
use MongoDB\Collection;
use Symfony\Bundle\FrameworkBundle\Console\Application;
use Symfony\Bundle\FrameworkBundle\KernelBrowser;
use Symfony\Bundle\FrameworkBundle\Test\WebTestCase;
use Symfony\Component\Console\Tester\CommandTester;

final class BookingAnalyticsTest extends WebTestCase
{
    private KernelBrowser $browser;
    private EntityManagerInterface $manager;
    private Connection $connection;
    private Collection $collection;
    private BookingAnalyticsRepository $repository;
    private string $schema;
    private User $user;
    private Restaurant $restaurant;
    private string $adminToken;
    private string $clientToken;

    protected function setUp(): void
    {
        if (getenv('RUN_ANALYTICS_TESTS') !== '1') {
            self::markTestSkipped('Set RUN_ANALYTICS_TESTS=1 with dedicated PostgreSQL and MongoDB *_test databases.');
        }
        $this->browser = self::createClient();
        $this->browser->disableReboot();
        $this->manager = self::getContainer()->get(EntityManagerInterface::class);
        $this->connection = $this->manager->getConnection();
        $database = getenv('MONGODB_DATABASE') ?: '';
        self::assertStringEndsWith('_test', $this->connection->getDatabase());
        self::assertStringEndsWith('_test', $database);
        $uri = getenv('MONGODB_URI') ?: 'mongodb://127.0.0.1:27017';
        $this->collection = (new Client($uri))->selectCollection($database, 'booking_analytics', ['typeMap' => ['root' => 'array', 'document' => 'array', 'array' => 'array']]);
        $this->collection->drop();
        $this->schema = 'analytics_'.bin2hex(random_bytes(6));
        $this->connection->executeStatement('CREATE SCHEMA '.$this->schema);
        $this->connection->executeStatement('SET search_path TO '.$this->schema);
        (new SchemaTool($this->manager))->createSchema($this->manager->getMetadataFactory()->getAllMetadata());
        $this->connection->executeStatement(<<<'SQL'
            CREATE TABLE IF NOT EXISTS messenger_messages (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, body TEXT NOT NULL,
                headers TEXT NOT NULL, queue_name VARCHAR(190) NOT NULL,
                created_at TIMESTAMP NOT NULL, available_at TIMESTAMP NOT NULL, delivered_at TIMESTAMP DEFAULT NULL)
            SQL);
        foreach (explode('-- statement', file_get_contents(__DIR__.'/../../config/sql/booking_analytics.sql')) as $sql) {
            $this->connection->executeStatement($sql);
        }
        $this->repository = self::getContainer()->get(BookingAnalyticsRepository::class);
        $this->repository->ensureIndexes();
        $this->user = (new User())->setEmail('analytics@example.test')->setPassword('test-hash')->setRoles(['ROLE_ADMIN'])
            ->setFirstName('Test')->setLastName('Admin')->setCreatedAt(new \DateTimeImmutable())->setGuestNumber(2);
        $this->adminToken = $this->user->issueApiToken();
        $client = (new User())->setEmail('client@example.test')->setPassword('test-hash')->setRoles(['ROLE_USER'])
            ->setFirstName('Test')->setLastName('Client')->setCreatedAt(new \DateTimeImmutable())->setGuestNumber(2);
        $this->clientToken = $client->issueApiToken();
        $this->restaurant = (new Restaurant())->setName('Analytics')->setDescription('Test')->setMaxGuest(50)->setOwner($this->user)
            ->setAmOpeningTime(['12:00', '14:00'])->setPmOpeningTime(['19:00', '21:00'])->setCreatedAt(new \DateTimeImmutable());
        foreach ([$this->user, $client, $this->restaurant] as $entity) $this->manager->persist($entity);
        $this->manager->flush();
    }

    protected function tearDown(): void
    {
        if (isset($this->schema)) {
            while ($this->connection->isTransactionActive()) $this->connection->rollBack();
            $this->connection->executeStatement('SET search_path TO public');
            $this->connection->executeStatement('DROP SCHEMA '.$this->schema.' CASCADE');
            $this->collection->drop();
        }
        parent::tearDown();
    }

    private function booking(string $date = '2026-10-25', string $hour = '12:00', int $guests = 2): Booking
    {
        $booking = (new Booking())->setClient($this->user)->setRestaurant($this->restaurant)->setGuestNumber($guests)
            ->setOrderDate(new \DateTime($date))->setOrderHour(new \DateTime($hour))->setCreatedAt(new \DateTimeImmutable())
            ->setAllergy('PRIVATE - must never enter analytics');
        $this->manager->persist($booking);
        $this->manager->flush();

        return $booking;
    }

    private function snapshots(): array
    {
        return array_map(static fn ($body) => json_decode($body, true, flags: JSON_THROW_ON_ERROR)['snapshot'],
            $this->connection->fetchFirstColumn("SELECT body FROM messenger_messages WHERE queue_name = 'analytics' ORDER BY id"));
    }

    private function consume(): void
    {
        $transport = self::getContainer()->get('messenger.transport.analytics');
        $bus = self::getContainer()->get('messenger.bus.default');
        while (true) {
            $found = false;
            foreach ($transport->get() as $envelope) {
                $found = true;
                self::assertInstanceOf(SyncBookingAnalytics::class, $envelope->getMessage());
                $bus->dispatch($envelope->with(new \Symfony\Component\Messenger\Stamp\ReceivedStamp('analytics')));
                $transport->ack($envelope);
            }
            if (!$found) break;
        }
    }

    private function statistics(array $filters = []): array
    {
        return self::getContainer()->get(BookingStatistics::class)->calculate(BookingStatisticsFilter::fromQuery($filters + [
            'from' => '2026-10-01', 'to' => '2026-10-31', 'restaurantId' => $this->restaurant->getId(),
        ]));
    }

    public function testOutboxRollsBackTogetherWithBookingAndContainsNoPersonalData(): void
    {
        $this->connection->beginTransaction();
        $booking = $this->booking();
        self::assertCount(1, $this->snapshots());
        self::assertArrayNotHasKey('allergy', $this->snapshots()[0]);
        self::assertArrayNotHasKey('clientId', $this->snapshots()[0]);
        $this->connection->rollBack();
        self::assertSame(0, (int) $this->connection->fetchOne('SELECT count(*) FROM booking'));
        self::assertCount(0, $this->snapshots());
        self::assertSame(0, (int) $this->connection->fetchOne('SELECT count(*) FROM booking_analytics_state'));
        self::assertSame(0, $this->collection->countDocuments());
    }

    public function testMessengerAggregationAndDateChangeAcrossDstBoundary(): void
    {
        $booking = $this->booking('2026-10-25', '12:00', 2);
        $this->booking('2026-10-25', '19:00', 5);
        $this->booking('2026-10-27', '12:00', 3);
        self::assertSame(3, $this->statistics()['synchronization']['pending']);
        $this->consume();
        $stats = $this->statistics();
        self::assertSame(['bookings' => 3, 'guests' => 10, 'averageGuests' => 3.33], $stats['totals']);
        self::assertCount(31, $stats['series']);
        self::assertSame(7, $stats['series'][24]['guests']);
        self::assertSame(0, $stats['synchronization']['pending']);
        self::assertNotNull($stats['synchronization']['lastSyncedAt']);
        self::assertSame(7, $this->statistics(['granularity' => 'week'])['series'][3]['guests']);
        self::assertSame(10, $this->statistics(['granularity' => 'month'])['series'][0]['guests']);
        $booking->setOrderDate(new \DateTime('2026-11-01'))->setGuestNumber(4)->setOrderHour(new \DateTime('19:30'));
        $this->manager->flush();
        $this->consume();
        self::assertSame(8, $this->statistics()['totals']['guests']);
        self::assertSame(4, $this->statistics(['from' => '2026-11-01', 'to' => '2026-11-01'])['totals']['guests']);
    }

    public function testReplayOutOfOrderAndDeletionNeverResurrectsBooking(): void
    {
        $booking = $this->booking();
        $id = $booking->getId();
        $booking->setGuestNumber(4);
        $this->manager->flush();
        $snapshots = $this->snapshots();
        $this->repository->synchronize($snapshots[1]);
        $this->repository->synchronize($snapshots[0]);
        $this->repository->synchronize($snapshots[1]);
        self::assertSame(4, $this->statistics()['totals']['guests']);
        self::assertSame(1, $this->collection->countDocuments());
        $this->manager->remove($booking);
        $this->manager->flush();
        $deleted = $this->snapshots()[2];
        $this->repository->synchronize($deleted);
        foreach ($snapshots as $snapshot) $this->repository->synchronize($snapshot);
        self::assertSame(0, $this->statistics()['totals']['bookings']);
        self::assertTrue($this->collection->findOne(['_id' => $id])['deleted']);
    }

    public function testReconciliationRestoresLostMongoCollectionIncludingTombstones(): void
    {
        $booking = $this->booking();
        $this->booking('2026-10-27');
        $this->manager->remove($booking);
        $this->manager->flush();
        $this->consume();
        $this->collection->drop();
        $application = new Application(self::$kernel);
        $command = new CommandTester($application->find('app:analytics:reconcile'));
        $command->execute([]);
        $command->assertCommandIsSuccessful();
        $this->consume();
        self::assertSame(2, $this->collection->countDocuments());
        self::assertSame(1, $this->statistics()['totals']['bookings']);
    }

    public function testMongoFailureLeavesOutboxAvailableForRecovery(): void
    {
        $this->booking();
        $unavailable = new BookingAnalyticsRepository('mongodb://127.0.0.1:1', 'unavailable_test');
        try {
            $unavailable->synchronize($this->snapshots()[0]);
            self::fail('MongoDB must be unavailable on port 1.');
        } catch (\MongoDB\Driver\Exception\ConnectionTimeoutException) {
            self::assertCount(1, $this->snapshots());
        }
        $this->consume();
        self::assertSame(1, $this->statistics()['totals']['bookings']);
    }

    public function testAdminOnlyValidationRestaurantIsolationAndEmptyPeriod(): void
    {
        $this->booking();
        $this->consume();
        // Other Messenger transports use PHP serialization, not JSON.
        $this->connection->executeStatement("INSERT INTO messenger_messages (body, headers, queue_name, created_at, available_at) VALUES ('not-json', '{}', 'async', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)");
        $path = '/api/admin/statistics/bookings?from=2026-10-01&to=2026-10-31';
        $this->browser->request('GET', $path);
        self::assertResponseStatusCodeSame(401);
        $this->browser->request('GET', $path, server: ['HTTP_X_AUTH_TOKEN' => $this->clientToken]);
        self::assertResponseStatusCodeSame(403);
        $headers = ['HTTP_X_AUTH_TOKEN' => $this->adminToken];
        $this->browser->request('GET', $path, server: $headers);
        self::assertResponseIsSuccessful();
        self::assertSame(1, json_decode($this->browser->getResponse()->getContent(), true)['totals']['bookings']);
        $this->browser->request('GET', $path.'&restaurantId=9999', server: $headers);
        self::assertResponseStatusCodeSame(404);
        $this->browser->request('GET', '/api/admin/statistics/bookings?from[]=bad', server: $headers);
        self::assertResponseStatusCodeSame(400);
        self::assertSame(0, $this->statistics(['restaurantId' => 9999])['totals']['bookings']);
        self::assertSame(0, $this->statistics(['from' => '2026-10-01', 'to' => '2026-10-02'])['totals']['bookings']);
    }

    public function testUnavailableAnalyticsReturns503WhileBookingsRemainWritable(): void
    {
        self::getContainer()->set(BookingStatistics::class, new BookingStatistics(
            new BookingAnalyticsRepository('mongodb://127.0.0.1:1', 'unavailable_test'), $this->connection,
        ));
        $this->browser->request('GET', '/api/admin/statistics/bookings', server: ['HTTP_X_AUTH_TOKEN' => $this->adminToken]);
        self::assertResponseStatusCodeSame(503);
        self::assertResponseHeaderSame('Retry-After', '30');
        $this->booking();
        self::assertCount(1, $this->snapshots());
        $this->consume();
        self::assertSame(1, $this->collection->countDocuments(['deleted' => false]));
    }

    public function testLegacyImportAndFailureQueueRoundTrip(): void
    {
        $this->connection->executeStatement('ALTER TABLE booking DISABLE TRIGGER booking_analytics_capture');
        $this->booking('2026-10-25', '15:00');
        $this->connection->executeStatement('ALTER TABLE booking ENABLE TRIGGER booking_analytics_capture');
        self::assertCount(0, $this->snapshots());
        $command = new CommandTester((new Application(self::$kernel))->find('app:analytics:reconcile'));
        $command->execute([]);
        $command->assertCommandIsSuccessful();
        self::assertSame('unknown', $this->snapshots()[0]['service']);
        $failed = self::getContainer()->get('messenger.transport.analytics_failed');
        $envelope = new \Symfony\Component\Messenger\Envelope(new SyncBookingAnalytics($this->snapshots()[0]));
        $failed->send($envelope->with(new \Symfony\Component\Messenger\Stamp\RedeliveryStamp(10)));
        self::assertSame(1, $this->statistics()['synchronization']['failed']);
        foreach ($failed->get() as $retry) {
            self::assertSame(10, $retry->last(\Symfony\Component\Messenger\Stamp\RedeliveryStamp::class)->getRetryCount());
            self::getContainer()->get('messenger.transport.analytics')->send($retry);
            $failed->ack($retry);
        }
        $this->consume();
        self::assertSame(1, $this->statistics()['totals']['bookings']);
        self::assertSame(0, $this->statistics()['synchronization']['failed']);
    }
}
